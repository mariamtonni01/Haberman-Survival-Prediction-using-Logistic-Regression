import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.mlab as mlt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn import metrics
from sklearn.metrics import classification_report
from sklearn.metrics import confusion_matrix,accuracy_score
from sklearn.metrics import roc_auc_score
from sklearn.metrics import roc_curve

"""**File Upload**"""

from google.colab import files
upload_file = files.upload()

f = pd.read_csv('synthetic_haberman_dataset.csv')

f

f.head()

"""**Feature Selection**"""

x =f.iloc[:,0:3]
y =f.iloc[:,-1]

"""**Train Test Split**"""

x

y

x_train,x_test,y_train,y_test = train_test_split(x,y,test_size = 0.20,random_state = 9)

x_train

x_test

y_train

y_test

"""**Model Training**"""

import sklearn
sklearn.set_config(print_changed_only=False)

lg= LogisticRegression()
lg.fit(x_train,y_train)

"""**Checking train test**"""

lg.predict(x_test)

y_test

print('Coefficients:', lg.coef_)
print('Intercept:', lg.intercept_)

prediction = lg.predict(x_test)
print('Classification Report:\n',classification_report(y_test, prediction))

print('Confusion Matrix:\n',confusion_matrix(y_test, prediction))
print('Accuracy Score:',accuracy_score(y_test, prediction))
print("Precision:",metrics.precision_score(y_test, prediction))
print("Recall:",metrics.recall_score(y_test,prediction))

# name  of classes
class_names=[1,2]
fig, ax = plt.subplots()
tick_marks = np.arange(len(class_names))
plt.xticks(tick_marks, class_names)
plt.yticks(tick_marks, class_names)
###create heatmap
sns.heatmap(pd.DataFrame(confusion_matrix(y_test, prediction)), annot=True, cmap="YlGnBu" ,fmt='g')
ax.xaxis.set_label_position("top")
plt.tight_layout()
plt.title('Confusion Matrix', y=1.1)
plt.ylabel('Actual label')
plt.xlabel('Predicted label')
plt.show()

logit_roc_auc = roc_auc_score(y_test, lg.predict(x_test))
fpr, tpr, thresholds = roc_curve(y_test, lg.predict_proba(x_test)[:,1], pos_label=2)
plt.figure()
plt.plot(fpr, tpr, label='Logistic Regression (area = %0.2f)' % logit_roc_auc)
plt.plot([0, 1], [0, 1],'r--')
plt.xlim([0.0, 1.0])
plt.ylim([0.0, 1.05])
plt.xlabel('False Positive Rate')
plt.ylabel('True Positive Rate')
plt.title('Receiver Operating Characteristic (ROC)')
plt.legend(loc="lower right")
plt.savefig('Log_ROC')
plt.show()

